"""Build the single-file Kaggle kernel `track_count.py` from `track_count_main.py`.

A Kaggle script kernel is one file, so the shared counting code (manzil/perception/counting.py)
is inlined at the `# @@INLINE <path>@@` marker. tests/test_counting.py checks that the committed
track_count.py is up to date. Run from the repository root:

    python kaggle/yolo_track/build.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MARK = re.compile(r"^# @@INLINE (\S+)@@$", re.M)


def build() -> str:
    src = (HERE / "track_count_main.py").read_text()

    def inline(m):
        body = (ROOT / m.group(1)).read_text()
        body = body.replace("from __future__ import annotations\n", "")
        return f"# ---- begin inlined {m.group(1)} (generated by build.py, do not edit) ----\n" \
               f"{body}# ---- end inlined {m.group(1)} ----\n"

    header = ("# GENERATED by kaggle/yolo_track/build.py from track_count_main.py. Do not edit.\n"
              "# ruff: noqa\n")
    return header + MARK.sub(inline, src)


if __name__ == "__main__":
    (HERE / "track_count.py").write_text(build())
    print("wrote", HERE / "track_count.py")
