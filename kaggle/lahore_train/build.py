"""Build the single-file Kaggle kernel `lahore_train.py` from `lahore_train_main.py`.

A Kaggle script kernel is one file, so the shared counting code (manzil/perception/counting.py)
is inlined at the `# @@INLINE <path>@@` marker. tests/test_w2_linking.py checks that the committed
lahore_train.py is up to date. Run from the repository root:

    python kaggle/lahore_train/build.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MARK = re.compile(r"^# @@INLINE (\S+)@@$", re.M)


def build() -> str:
    src = (HERE / "lahore_train_main.py").read_text()

    def inline(m):
        body = (ROOT / m.group(1)).read_text()
        body = body.replace("from __future__ import annotations\n", "")
        return f"# ---- begin inlined {m.group(1)} (generated by build.py, do not edit) ----\n" \
               f"{body}# ---- end inlined {m.group(1)} ----\n"

    header = ("# GENERATED by kaggle/lahore_train/build.py from lahore_train_main.py. "
              "Do not edit.\n# ruff: noqa\n")
    return header + MARK.sub(inline, src)


if __name__ == "__main__":
    (HERE / "lahore_train.py").write_text(build())
    print("wrote", HERE / "lahore_train.py")
