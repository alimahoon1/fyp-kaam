"""Network reader: intersections, signal links, green phases and conflicts from a ``.net.xml``.

PLAN task 1.4. Everything is read from the SUMO network file, so the same code runs on the
synthetic grid and on a later Lahore network with no hard-coded IDs.

Terms used across Manzil:

- **link**: one controlled movement (incoming lane -> outgoing lane) at a traffic light, numbered
  by SUMO's TLS link index (the position in the signal state string such as ``"GGgrr..."``).
- **approach**: one incoming edge of an intersection, with its lanes.
- **green phase**: a phase of the network's signal program that gives green to at least one
  link and has no yellow. Controllers choose among these; yellow and all-red transitions are
  generated by the safety filter, not chosen by controllers.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

import sumolib

GREEN_CHARS = frozenset("Gg")


@dataclass(frozen=True)
class Link:
    index: int  # TLS link index (position in the state string)
    from_lane: str
    to_lane: str
    from_edge: str
    to_edge: str
    direction: str  # SUMO direction code: s, l, r, t, L, R
    junction_index: int  # index into the junction's request matrix


@dataclass(frozen=True)
class GreenPhase:
    index: int  # Manzil phase id: position among the green phases (0, 1, ...)
    program_phase: int  # position in the original SUMO program
    state: str
    default_duration_s: float

    def green_links(self) -> frozenset[int]:
        return frozenset(i for i, c in enumerate(self.state) if c in GREEN_CHARS)


@dataclass(frozen=True)
class Approach:
    edge_id: str
    lanes: tuple[str, ...]
    north_south: bool


@dataclass
class Intersection:
    tls_id: str
    junction_ids: tuple[str, ...]
    program_id: str
    links: tuple[Link, ...]
    approaches: tuple[Approach, ...]
    green_phases: tuple[GreenPhase, ...]
    outgoing_lanes: tuple[str, ...]
    # Junction request matrices, by junction index: foes[i] = links in conflict with i,
    # yields[i] = links that i must give way to.
    _foes: dict[int, frozenset[int]] = field(default_factory=dict, repr=False)
    _yields: dict[int, frozenset[int]] = field(default_factory=dict, repr=False)

    @property
    def num_links(self) -> int:
        return len(self.links)

    @property
    def incoming_lanes(self) -> tuple[str, ...]:
        return tuple(lane for a in self.approaches for lane in a.lanes)

    def are_foes(self, link_a: int, link_b: int) -> bool:
        ja, jb = self.links[link_a].junction_index, self.links[link_b].junction_index
        return jb in self._foes.get(ja, frozenset())

    def must_yield(self, link_a: int, link_b: int) -> bool:
        """True if link ``a`` has to give way to link ``b`` (SUMO request "response" bit)."""
        ja, jb = self.links[link_a].junction_index, self.links[link_b].junction_index
        return jb in self._yields.get(ja, frozenset())

    def conflicts_in(self, state: str) -> list[tuple[int, int]]:
        """Pairs of conflicting links that are green together without a legal yield.

        Two foe links may only be green at the same time if one of them is a minor green ``g``
        that must yield to the other (for example a permissive left turn facing oncoming
        traffic). Any other simultaneous green of foes is a safety violation.
        """
        if len(state) != self.num_links:
            raise ValueError(f"{self.tls_id}: state {state!r} has wrong length")
        green = [i for i, c in enumerate(state) if c in GREEN_CHARS]
        bad = []
        for pos, a in enumerate(green):
            for b in green[pos + 1 :]:
                if not self.are_foes(a, b):
                    continue
                a_yields = state[a] == "g" and self.must_yield(a, b)
                b_yields = state[b] == "g" and self.must_yield(b, a)
                if not (a_yields or b_yields):
                    bad.append((a, b))
        return bad


@dataclass
class NetworkModel:
    net_file: Path
    network_id: str  # file name + short content hash, used to tag snapshots and runs
    intersections: dict[str, Intersection]
    net: sumolib.net.Net = field(repr=False)

    @property
    def tls_ids(self) -> list[str]:
        return sorted(self.intersections)

    @classmethod
    def from_file(cls, net_file: str | Path) -> NetworkModel:
        from manzil.scenarios.grid import content_sha256

        net_file = Path(net_file)
        net = sumolib.net.readNet(str(net_file), withPrograms=True)
        requests = _read_requests(net_file)
        intersections = {
            tls.getID(): _build_intersection(net, tls, requests) for tls in net.getTrafficLights()
        }
        network_id = f"{net_file.name}#{content_sha256(net_file)[:12]}"
        return cls(net_file, network_id, intersections, net)


def _read_requests(net_file: Path) -> dict[str, dict[int, tuple[str, str]]]:
    """junction id -> {request index: (response bits, foes bits)} straight from the XML."""
    out: dict[str, dict[int, tuple[str, str]]] = {}
    for _, elem in ET.iterparse(net_file, events=("end",)):
        if elem.tag == "junction" and elem.get("type") != "internal":
            reqs = {
                int(r.get("index")): (r.get("response"), r.get("foes"))
                for r in elem.findall("request")
            }
            if reqs:
                out[elem.get("id")] = reqs
            elem.clear()
    return out


def _bits_to_set(bits: str) -> frozenset[int]:
    # SUMO writes bit strings with the highest index first.
    n = len(bits)
    return frozenset(n - 1 - pos for pos, c in enumerate(bits) if c == "1")


def _north_south(edge) -> bool:
    (x0, y0), (x1, y1) = edge.getFromNode().getCoord(), edge.getToNode().getCoord()
    return abs(y1 - y0) > abs(x1 - x0)


def _build_intersection(net, tls, requests) -> Intersection:
    links: dict[int, Link] = {}
    junctions: set[str] = set()
    for from_lane, to_lane, idx in tls.getConnections():
        conns = [c for c in from_lane.getOutgoing() if c.getToLane() is to_lane]
        if not conns:
            raise ValueError(f"{tls.getID()}: no connection for link {idx}")
        conn = conns[0]
        junction = from_lane.getEdge().getToNode().getID()
        junctions.add(junction)
        links[idx] = Link(
            index=idx,
            from_lane=from_lane.getID(),
            to_lane=to_lane.getID(),
            from_edge=from_lane.getEdge().getID(),
            to_edge=to_lane.getEdge().getID(),
            direction=conn.getDirection(),
            junction_index=conn.getJunctionIndex(),
        )
    if sorted(links) != list(range(len(links))):
        raise ValueError(f"{tls.getID()}: link indices are not 0..n-1")
    if len(junctions) != 1:
        # Joined traffic lights spanning several junctions are not supported yet; the
        # request matrix lookup below assumes one junction per traffic light.
        raise NotImplementedError(f"{tls.getID()}: controls several junctions {sorted(junctions)}")
    (junction,) = junctions

    foes, yields = {}, {}
    for j_idx, (response, foe_bits) in requests.get(junction, {}).items():
        foes[j_idx] = _bits_to_set(foe_bits)
        yields[j_idx] = _bits_to_set(response)

    approach_lanes: dict[str, list[str]] = {}
    for link in links.values():
        lanes = approach_lanes.setdefault(link.from_edge, [])
        if link.from_lane not in lanes:
            lanes.append(link.from_lane)
    approaches = tuple(
        Approach(edge, tuple(sorted(lanes)), _north_south(net.getEdge(edge)))
        for edge, lanes in sorted(approach_lanes.items())
    )
    outgoing = tuple(sorted({link.to_lane for link in links.values()}))

    programs = tls.getPrograms()
    program_id = sorted(programs)[0]
    greens = []
    for p_idx, phase in enumerate(programs[program_id].getPhases()):
        state = phase.state
        if "y" in state.lower() or not any(c in GREEN_CHARS for c in state):
            continue
        greens.append(GreenPhase(len(greens), p_idx, state, float(phase.duration)))
    if len(greens) < 2:
        raise ValueError(f"{tls.getID()}: needs at least two green phases, found {len(greens)}")

    return Intersection(
        tls_id=tls.getID(),
        junction_ids=(junction,),
        program_id=program_id,
        links=tuple(links[i] for i in range(len(links))),
        approaches=approaches,
        green_phases=tuple(greens),
        outgoing_lanes=outgoing,
        _foes=foes,
        _yields=yields,
    )
